import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const defaultRoot = path.resolve(__dirname, '..', '..');

function normalizePath(filePath) {
  return filePath.split(path.sep).join('/');
}

function resolveFromRoot(root, filePath) {
  return path.resolve(root, filePath);
}

function asArray(value, fieldName) {
  if (!Array.isArray(value)) {
    throw new Error(`Prompt definition field "${fieldName}" must be an array.`);
  }
  return value;
}

function assertString(value, fieldName) {
  if (typeof value !== 'string' || value.length === 0) {
    throw new Error(`Prompt definition field "${fieldName}" must be a non-empty string.`);
  }
}

function validatePromptDefinition(definition, filePath) {
  for (const field of ['id', 'title', 'sourcePath', 'docsPath', 'runtimePath', 'runtimeExportName']) {
    assertString(definition[field], `${filePath}:${field}`);
  }

  asArray(definition.purpose, `${filePath}:purpose`);
  asArray(definition.designPrinciples, `${filePath}:designPrinciples`);
  asArray(definition.promptSections, `${filePath}:promptSections`);
  asArray(definition.iterationLog, `${filePath}:iterationLog`);

  if (!definition.contextPacket || typeof definition.contextPacket !== 'object') {
    throw new Error(`Prompt definition field "${filePath}:contextPacket" must be an object.`);
  }
}

export async function loadPromptDefinitions(directory = path.join(defaultRoot, 'prompts')) {
  const entries = await readdir(directory, { withFileTypes: true });
  const definitions = [];

  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.json')) {
      continue;
    }

    const filePath = path.join(directory, entry.name);
    const raw = await readFile(filePath, 'utf8');
    const definition = JSON.parse(raw);
    validatePromptDefinition(definition, normalizePath(filePath));
    definitions.push(definition);
  }

  return definitions.sort((left, right) => left.id.localeCompare(right.id));
}

export function buildFullPrompt(definition) {
  return definition.promptSections.map((section) => section.content.trim()).join('\n\n').trim();
}

function bulletList(items) {
  return items.map((item) => `- ${item}`).join('\n');
}

export function renderPromptDocs(definition) {
  const principleSections = definition.designPrinciples
    .map((principle, index) => `${index + 1}. **${principle.title}.** ${principle.body}`)
    .join('\n');

  const sectionRationale = definition.promptSections
    .map(
      (section) =>
        `### ${section.heading}\n\n**${section.commentaryTitle}.** ${section.commentary}\n\n` +
        `\`\`\`${section.language}\n${section.content.trim()}\n\`\`\``
    )
    .join('\n\n');

  const iterationLog = definition.iterationLog
    .map((entry) => `- ${entry.date}: ${entry.change} Reason: ${entry.reason}`)
    .join('\n');

  return `# ${definition.title}

> Generated from \`${definition.sourcePath}\`. Do not edit this file directly.

## Purpose

${bulletList(definition.purpose)}

## Design Principles

${principleSections}

## Section Rationale

${sectionRationale}

## Context Packet

${definition.contextPacket.description}

**${definition.contextPacket.commentaryTitle}.** ${definition.contextPacket.commentary}

\`\`\`text
${definition.contextPacket.template.trim()}
\`\`\`

## Full Prompt

\`\`\`text
${buildFullPrompt(definition)}
\`\`\`

## Iteration Log

${iterationLog}
`;
}

function escapeTemplateLiteral(value) {
  return value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

export function renderRuntimePrompt(definition) {
  return `// This file is generated by \`npm run prompts:generate\`.
// Source: ${definition.sourcePath}
// Do not edit this file directly.

export const ${definition.runtimeExportName} = \`${escapeTemplateLiteral(buildFullPrompt(definition))}\`;
`;
}

async function readIfExists(filePath) {
  try {
    return await readFile(filePath, 'utf8');
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      return null;
    }
    throw error;
  }
}

function sameGeneratedContent(actual, expected) {
  return actual !== null && actual.replace(/\r\n/g, '\n') === expected;
}

export async function generatePromptArtifacts(options = {}) {
  const root = options.root ? path.resolve(options.root) : defaultRoot;
  const definitions = await loadPromptDefinitions(path.join(root, 'prompts'));
  const results = [];

  for (const definition of definitions) {
    const docsContent = renderPromptDocs(definition);
    const runtimeContent = renderRuntimePrompt(definition);
    const docsPath = resolveFromRoot(root, definition.docsPath);
    const runtimePath = resolveFromRoot(root, definition.runtimePath);
    const currentDocs = await readIfExists(docsPath);
    const currentRuntime = await readIfExists(runtimePath);

    await mkdir(path.dirname(docsPath), { recursive: true });
    await mkdir(path.dirname(runtimePath), { recursive: true });
    await writeFile(docsPath, docsContent);
    await writeFile(runtimePath, runtimeContent);

    results.push({
      id: definition.id,
      docsChanged: currentDocs !== docsContent,
      runtimeChanged: currentRuntime !== runtimeContent,
      docsPath: definition.docsPath,
      runtimePath: definition.runtimePath
    });
  }

  return results;
}

export async function checkPromptArtifacts(options = {}) {
  const root = options.root ? path.resolve(options.root) : defaultRoot;
  const definitions = await loadPromptDefinitions(path.join(root, 'prompts'));
  const stalePaths = [];

  for (const definition of definitions) {
    const expectedDocs = renderPromptDocs(definition);
    const expectedRuntime = renderRuntimePrompt(definition);
    const docsPath = resolveFromRoot(root, definition.docsPath);
    const runtimePath = resolveFromRoot(root, definition.runtimePath);

    if (!sameGeneratedContent(await readIfExists(docsPath), expectedDocs)) {
      stalePaths.push(definition.docsPath);
    }
    if (!sameGeneratedContent(await readIfExists(runtimePath), expectedRuntime)) {
      stalePaths.push(definition.runtimePath);
    }
  }

  return stalePaths;
}

async function runCli() {
  const command = process.argv[2] ?? 'check';

  if (command === 'generate') {
    const results = await generatePromptArtifacts();
    for (const result of results) {
      const changed = result.docsChanged || result.runtimeChanged ? 'updated' : 'unchanged';
      console.log(`${result.id}: ${changed}`);
    }
    return;
  }

  if (command === 'check') {
    const stalePaths = await checkPromptArtifacts();
    if (stalePaths.length > 0) {
      console.error('Prompt artifacts are out of date. Run `npm run prompts:generate`.');
      for (const stalePath of stalePaths) {
        console.error(`- ${stalePath}`);
      }
      process.exit(1);
    }
    console.log('Prompt artifacts are up to date.');
    return;
  }

  console.error('Usage: node scripts/prompt-generation.mjs [generate|check]');
  process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  runCli().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
